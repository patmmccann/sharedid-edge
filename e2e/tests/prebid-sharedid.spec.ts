test('consent only through Prebid.js, with no euconsent-v2 cookie: the endpoint sets the ID or not as gdpr_consent says', async ({ page, context, sid }) => {
  // The CMP keeps the TC string out of cookies (?tcfCookie=none), and gives the publisher consent for purpose 1 only:
  // SharedID Edge's publisher mode needs one of purposes 2-10 too. Prebid.js still stores and syncs the ID (its
  // tcfControl needs only purpose 1 for that).
  // Without pixelConsent, the endpoint sees no TC string, and no gdpr: nothing tells it to deny.
  let response = await visit(page, '/?consent=purpose1Only&tcfCookie=none&pixelConsent=off');
  expect(await cookie(context, 'euconsent-v2')).toBeUndefined();
  expect(syncParams(await onlySync(sid)).map(([name]) => name)).toEqual(['id']);
  expect(response.headers()['x-sharedid-status']).toBeUndefined();
  const id = (await cookie(context, '_pubcid_sv'))?.value;
  expect(id).toMatch(/^[0-9a-f-]{36}$/);

  // With pixelConsent, the sync carries gdpr=1 and the TC string: the endpoint denies, and deletes the ID cookies.
  sid.reset();
  response = await visit(page, '/?consent=purpose1Only&tcfCookie=none');
  const sync = await onlySync(sid);
  expect(syncParams(sync).slice(1)).toEqual([['gdpr', '1'], ['gdpr_consent', tcString('purpose1Only')]]);
  expect(syncedId(sync)).toBe(id);
  expect(response.headers()['x-sharedid-status']).toBe('denied: tcf: no publisher consent or legitimate interest for any of purposes 2-10');
  const deleted = (await response.headerValues('set-cookie')).filter(c => /^_pubcid(_sv)?=;.*Max-Age=0/.test(c)).map(c => c.split('=')[0]);
  expect(new Set(deleted)).toEqual(new Set(['_pubcid', '_pubcid_sv']));
  expect(await cookie(context, '_pubcid_sv')).toBeUndefined();
  await expect.poll(() => cookie(context, '_pubcid')).toBeUndefined();

  // The visitor gives the publisher consent for purposes 1-10: the next sync sets the ID again.
  sid.reset();
  response = await visit(page, '/?tcfCookie=none');
  expect(await cookie(context, 'euconsent-v2')).toBeUndefined();
  expect(syncParams(await onlySync(sid)).slice(1)).toEqual([['gdpr', '1'], ['gdpr_consent', tcString('given')]]);
  expect(response.headers()['x-sharedid-status']).toBeUndefined();
  const restored = (await cookie(context, '_pubcid_sv'))?.value;
  expect(restored).toMatch(/^[0-9a-f-]{36}$/);
  expect((await cookie(context, '_pubcid'))?.value).toBe(restored);
});

