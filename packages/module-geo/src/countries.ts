/** ISO 3166-1 alpha-2 code to alpha-3 code, for every officially assigned country code. */
export const ALPHA_3: ReadonlyMap<string, string> = new Map(TABLE.split(' ').map(entry => [entry.slice(0, 2), entry.slice(2)]));

/** The ISO 3166-1 alpha-3 code for an alpha-2 code (in either case), or undefined if it isn't assigned. */
export function alpha3(alpha2: string): string | undefined {
  return ALPHA_3.get(alpha2.toUpperCase());
}
