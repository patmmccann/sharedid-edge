// Builds a deployment's module list with opt-in modules: the built-in modules (@sharedid-edge/modules, or its
// /bowser variant), plus module packages named as `<package>#<export>`, such as `@sharedid-edge/module-ec#ecModule`
// or a vendor module. The bundled adapters (`--module`, see scripts/bundle-adapter.mjs) point their
// `@sharedid-edge/modules` import at the generated list; the Worker uses a generated entry point (`--worker`).
//
//   node scripts/module-list.mjs <dir> [--bowser] [--worker] [--vendor-modules] [--module <package>#<export>]…
//   node scripts/module-list.mjs --print-vendor-modules   (the vendor modules, comma-separated, for SID_MODULE_PACKAGES)
//
// writes <dir>/modules.mjs (and with --worker, <dir>/worker.ts for `wrangler deploy <dir>/worker.ts`, run from the
// Cloudflare package). --vendor-modules adds every module in packages/vendor-modules/ (the conformance suite's build).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { vendorModules } from './vendor-modules.mjs';

const ROOT = join(import.meta.dirname, '..');

/**
 * Parses `<package>#<export>`.
 *
 * @param {string} spec
 * @returns {{ pkg: string, name: string }}
 */
export function parseModuleSpec(spec) {
  const match = /^((?:@[a-z0-9][\w.-]*\/)?[a-z0-9][\w.-]*)#([A-Za-z_$][\w$]*)$/.exec(spec.trim());
  if (match === null) throw new Error(`"${spec}" isn't a module: use <package>#<export>, like @sharedid-edge/module-ec#ecModule`);
  return { pkg: match[1], name: match[2] };
}

/** Every vendor module in packages/vendor-modules/, as `<package>#<export>` (its sharedidEdge block's `export`). */
export function vendorModuleSpecs() {
  return vendorModules()
    .map(({ folder, meta }) => `${JSON.parse(readFileSync(join(ROOT, folder, 'package.json'), 'utf8')).name}#${typeof meta.export === 'string' ? meta.export : ''}`)
    .sort();
}

/** An import path for a package, resolved from the repository: absolute, so an alias can't loop back to it. */
const resolved = specifier => JSON.stringify(fileURLToPath(import.meta.resolve(specifier)));

/**
 * Writes `<dir>/modules.mjs`, exporting `builtInModules`: the built-in list plus `modules`, in order. Returns its path.
 *
 * @param {string} dir
 * @param {{ bowser?: boolean, modules: string[] }} options
 */
export function writeModuleList(dir, { bowser = false, modules }) {
  const parsed = modules.map(parseModuleSpec);
  const lines = [
    '// Generated by scripts/module-list.mjs: the built-in modules plus opt-in ones. Don\'t edit; regenerate.',
    `import { builtInModules as base } from ${resolved(bowser ? '@sharedid-edge/modules/bowser' : '@sharedid-edge/modules')};`,
    ...parsed.map(({ pkg, name }, i) => `import { ${name} as m${String(i)} } from ${resolved(pkg)};`),
    `export const builtInModules = Object.freeze([...base, ${parsed.map((_, i) => `m${String(i)}`).join(', ')}]);`,
    ''
  ];
  mkdirSync(dir, { recursive: true });
  const file = join(dir, 'modules.mjs');
  writeFileSync(file, lines.join('\n'));
  return file;
}

/** Writes `<dir>/worker.ts`, the Worker's entry point with `<dir>/modules.mjs`, for a Cloudflare package at `pkgDir`. */
export function writeWorkerEntry(dir, pkgDir) {
  const worker = relative(dir, join(pkgDir, 'src/worker.js')).split('\\').join('/');
  const file = join(dir, 'worker.ts');
  writeFileSync(file, [
    '// Generated by scripts/module-list.mjs: the Worker with the built-in modules plus opt-in ones. Don\'t edit; regenerate.',
    `import { createWorker } from '${worker.startsWith('.') ? worker : `./${worker}`}';`,
    "import { builtInModules } from './modules.mjs';",
    'export default createWorker(builtInModules);',
    ''
  ].join('\n'));
  return file;
}

if (process.argv[1] !== undefined && import.meta.filename === process.argv[1]) {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: { 'print-vendor-modules': { type: 'boolean', default: false }, bowser: { type: 'boolean', default: false }, worker: { type: 'boolean', default: false }, 'vendor-modules': { type: 'boolean', default: false }, module: { type: 'string', multiple: true, default: [] } }
  });
  if (values['print-vendor-modules']) {
    console.log(vendorModuleSpecs().join(','));
    process.exit(0);
  }
  if (positionals.length !== 1) {
    console.error('usage: node scripts/module-list.mjs <dir> [--bowser] [--worker] [--vendor-modules] [--module <package>#<export>]…');
    process.exit(2);
  }
  const dir = resolve(positionals[0]);
  const modules = [...(values['vendor-modules'] ? vendorModuleSpecs() : []), ...values.module];
  console.log(`Module list: ${relative(process.cwd(), writeModuleList(dir, { bowser: values.bowser, modules }))} (built-in modules${modules.length === 0 ? '' : ` plus ${modules.join(', ')}`})`);
  if (values.worker) console.log(`Worker entry: ${relative(process.cwd(), writeWorkerEntry(dir, process.cwd()))}`);
}
